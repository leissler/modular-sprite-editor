"""Play two builds of the SNES demo ROM in Mesen 2 and check that they draw the same, frame by frame.

ROMs built on different systems are not byte for byte the same: wlalink places sections of the same size in the order
its C library's qsort leaves them (its comparison never answers "equal"), so the data chunks and many small code
sections land elsewhere on macOS, Linux and Windows. What a build draws does not depend on that. Both ROMs play the same
button presses, through every view of the demo (the first scene, animations with hitboxes and every look, frames,
modules), and must show the same sprite table (the PPU's OAM) on every video frame, the same palettes whenever they
change and the same video memory at the end (and so as many lag frames). tools/check_snes_rom.py checks the runtime in a ROM
against the editor; this check carries that over to a ROM built elsewhere, such as the Windows kit's.

Usage (from the repository root):
    python3 tools/compare_snes_roms.py REFERENCE.sfc OTHER.sfc [--mesen PATH]
"""

from __future__ import annotations

import argparse
import sys
import tempfile
from pathlib import Path
from typing import List, Tuple

sys.path.insert(0, str(Path(__file__).resolve().parent))

from check_snes_rom import find_mesen, run_mesen, symbols  # noqa: E402

# (video frame, buttons held from it for PRESS frames): the demo acts on a press (held for 16 frames, LEFT / RIGHT
# repeat); it starts on the first scene, playing.
PRESS = 4
PRESSES: List[Tuple[int, str]] = [
    (480, "down"),  # animations
    (720, "right"), (740, "right"), (760, "right"),
    (900, "b"),  # hitboxes and points
    (1020, "x"), (1140, "x"),  # the looks: mappings and palette swaps
    (1260, "a"), (1320, "a"),  # pause, play on
    (1380, "down"),  # frames
    (1500, "right"), (1520, "right"),
    (1620, "down"),  # modules
    (1740, "right"), (1760, "right"),
    (1860, "up"), (1880, "up"), (1900, "up"),  # back to the scenes
]
FRAMES = 2100

LUA = r"""-- Generated by tools/compare_snes_roms.py: the PPU's OAM whenever it changes, the palettes whenever they change,
-- the lag frames after the first second and video memory at the end.
local HEX = {}
for i = 0, 255 do HEX[i] = string.format("%02x", i) end
local function hex(mem, base, size)
  local parts = {}
  for i = 0, size - 1 do parts[#parts + 1] = HEX[emu.read(base + i, mem, false)] end
  return table.concat(parts)
end
-- Mesen fills video memory, the sprite table and the palettes with random values at power-on: both ROMs start from
-- zeros (the demo writes what it uses; what it does not stays the same).
for i = 0, 0xFFFF do emu.write(i, 0, emu.memType.snesVideoRam) end
for i = 0, 543 do emu.write(i, 0, emu.memType.snesSpriteRam) end
for i = 0, 511 do emu.write(i, 0, emu.memType.snesCgRam) end
local PRESSES = {@PRESSES@}
local frame, oam, cgram, lag = 0, "", "", 0
emu.addEventCallback(function()
  local held = {}
  for _, press in ipairs(PRESSES) do
    if frame >= press[1] and frame < press[1] + @PRESS@ then held[press[2]] = true end
  end
  emu.setInput(held, 0)
end, emu.eventType.inputPolled)
emu.addEventCallback(function()
  frame = frame + 1
  if frame == 60 then lag = emu.read16(@LAG@, emu.memType.snesMemory, false) end
  local now = hex(emu.memType.snesSpriteRam, 0, 544)
  if now ~= oam then print("oam " .. frame .. " " .. now) oam = now end
  now = hex(emu.memType.snesCgRam, 0, 512)
  if now ~= cgram then print("cgram " .. frame .. " " .. now) cgram = now end
  if frame >= @FRAMES@ then
    print("lag " .. (emu.read16(@LAG@, emu.memType.snesMemory, false) - lag))
    print("vram " .. hex(emu.memType.snesVideoRam, 0, 0x10000))
    emu.stop(0)
  end
end, emu.eventType.endFrame)
"""


def lag_counter(rom: Path) -> int:
    """Where PVSnesLib's vertical blank handler counts lag frames (lag_frame_counter: from the ROM's symbols when they
    are next to it, else where PVSnesLib 4.6 keeps it)."""
    sym = rom.with_suffix(".sym")
    return symbols(sym).get("lag_frame_counter", 0x35) if sym.exists() else 0x35


def play(mesen: str, rom: Path, work: Path) -> List[str]:
    presses = ", ".join(f'{{{frame}, "{button}"}}' for frame, button in PRESSES)
    script = work / f"{rom.stem}.lua"
    script.write_text(LUA.replace("@PRESSES@", presses).replace("@PRESS@", str(PRESS))
                      .replace("@FRAMES@", str(FRAMES)).replace("@LAG@", hex(lag_counter(rom))))
    result = run_mesen(mesen, rom, script)
    lines = result.stdout.splitlines()
    if not any(line.startswith("vram ") for line in lines):
        raise RuntimeError(f"Mesen did not finish {rom.name}:\n" + (result.stdout + result.stderr)[-2000:])
    return lines


def difference(a: str, b: str) -> str:
    """Where two trace lines part: the video frame of a change, or the first byte that is not the same."""
    kind, *rest_a = a.split(" ")
    rest_b = b.split(" ")[1:]
    if kind != b.split(" ")[0] or len(rest_a) != len(rest_b):
        return f"{a[:40]}... / {b[:40]}..."
    where = "at the end" if kind in ("vram", "lag") else f"from video frame {rest_a[0]}"
    if kind != "vram" and rest_a[0] != rest_b[0]:
        return f"{kind} changes on video frame {rest_a[0]} / {rest_b[0]}"
    data_a, data_b = rest_a[-1], rest_b[-1]
    first = next((i for i in range(min(len(data_a), len(data_b))) if data_a[i] != data_b[i]), 0) // 2
    return f"{kind} {where}, byte {first:#06x}: {data_a[first * 2:first * 2 + 16]} / {data_b[first * 2:first * 2 + 16]}"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("reference", type=Path, help="The ROM that tools/check_snes_rom.py's build stands for.")
    parser.add_argument("other", type=Path, help="The ROM built elsewhere.")
    parser.add_argument("--mesen", help="The Mesen 2 executable (default: $MESEN, PATH, /Applications/Mesen.app).")
    args = parser.parse_args()
    mesen = find_mesen(args.mesen)
    if not mesen:
        print("needs Mesen 2 (--mesen)")
        return 2
    with tempfile.TemporaryDirectory() as tmp:
        work = Path(tmp)
        traces = [play(mesen, rom.resolve(), work) for rom in (args.reference, args.other)]
    reference, other = traces
    oams = sum(line.startswith("oam ") for line in reference)
    lag = [next(line for line in t if line.startswith("lag ")) for t in traces]
    for index, (a, b) in enumerate(zip(reference, other)):
        if a != b:
            print(f"{args.other.name} does not draw like {args.reference.name}: {difference(a, b)}")
            return 1
    if len(reference) != len(other):
        print(f"{args.other.name} differs from {args.reference.name}: {len(reference)} / {len(other)} lines")
        return 1
    print(f"{args.other.name} draws like {args.reference.name}: {FRAMES} video frames, {len(PRESSES)} presses through "
          f"every view, {oams} sprite tables, the palettes and video memory the same, "
          f"{lag[0].split()[1]} lag frames after the first second")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
