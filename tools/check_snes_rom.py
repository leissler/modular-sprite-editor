"""Build the SNES runtime into a ROM with PVSnesLib and check what it draws on the console against the host build of
the same runtime, which tests/test_snes_runtime_draw.py checks against the editor (needs PVSnesLib and Mesen 2;
neither is needed by the editor or its tests).

For each project: exports it (examples/snes/tools/export_snes.py) into a copy of the SNES demo with a probe program in
place of the demo's main.c and builds the ROM. Mesen's headless test runner plays it with a Lua script that reads the
OAM buffer and the PPU's OAM after every draw, then video memory and the palettes. The probe draws every frame at three
positions, each scene at a few moments with every mapping, one animation twice with ms_draw_anim_player_as (the second
time with another mapping and palette swap) and a game's own sprites (ms_add_hw_sprite) across the screen's edges,
timing each draw with the PPU's V counter; then it turns the colour
cycles (two added to the first palette when it has none) for 47 video frames and plays the first scene for ten
seconds, counting lag frames (frames the game was not ready for). Every OAM must equal the host build's byte for byte,
video memory the export's sprite tiles and the sprite palettes the host build's after as many palette ticks.

Usage (from the repository root):
    python3 tools/check_snes_rom.py [PROJECT.json ...] [--mesen PATH] [--pvsneslib DIR] [--keep DIR]
"""

from __future__ import annotations

import argparse
import os
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path
from typing import Dict, List, Optional, Tuple

REPO = Path(__file__).resolve().parents[1]
DEMO = REPO / "examples" / "snes" / "snes_demo"
sys.path.insert(0, str(REPO))
sys.path.insert(0, str(REPO / "examples" / "snes" / "tools"))

import export_snes  # noqa: E402
import snes_host  # noqa: E402
from models import Project  # noqa: E402

DEFAULT_PROJECTS = [REPO / "examples" / "sgdk" / "PoP_WW.json", REPO / "examples" / "adventurer" / "adventurer.json"]
POSITIONS = [(128, 112), (6, 10), (250, 216)]  # the middle of the screen, across the top-left and bottom-right edges
SCENE_TICKS = (0, 60, 300)
HOLD = 3  # video frames each draw stays: the script sees the whole buffer, and the PPU's OAM after the transfer
PLAY_FRAMES = 600
PALETTE_TICKS = 47  # with the cycles below: every cycle in a step other than its first
# Where scenes are drawn: centred, three quarters down (ui/scene_editor/ops.screen_origin, as the demos draw them).
SCENE_X, SCENE_Y = snes_host.SCREEN_W // 2, snes_host.SCREEN_H * 3 // 4
LINES_PER_FRAME = 262  # NTSC
LINE_US = 1364 / 21.477272  # a scanline: 1364 master cycles

PROBE_C = r"""/* Generated by tools/check_snes_rom.py: draws each item like snes_host's harness and holds it for a few video
   frames, timed with the V counter; the Lua script reads probe_state, probe_item, probe_lines and the OAM. */
#include <snes.h>
#include "modsprite.h"

#define PROBE_COUNT @COUNT@
#define PROBE_HOLD @HOLD@
#define PROBE_PALETTE_TICKS @TICKS@
#define REG_SLHV (*(vuint8 *)0x2137)
#define REG_OPVCT (*(vuint8 *)0x213D)

/* kind (0 frame, 1 scene, 2 versus, 3 sprite: index = tile, mapping = attribute, swap = large), index, mapping,
   swap, ticks, x, y, x2, y2 */
static const s16 probe_items[PROBE_COUNT * 9] = {
@ITEMS@
};

u16 probe_state;  /* 0 drawing, 1 the OAM buffer holds item probe_item, 2 playing the first scene, 3 done */
u16 probe_item;
u16 probe_lines;  /* scanlines the item's draw took */
u8 probe_latch;

static u16 probe_vcount(void)
{
    u16 v;

    probe_latch = REG_SLHV;    /* latch the counters */
    probe_latch = REG_STAT78;  /* the next OPVCT read gives the low byte */
    v = REG_OPVCT;
    v |= (u16)(REG_OPVCT & 1) << 8;
    return v;
}

int main(void)
{
    u16 i, t, start, now;
    const s16 *item;
    MS_ScenePlayer scene;
    MS_AnimPlayer player;

    probe_state = 0;
    ms_init();
    setScreenOn();
    for (i = 0; i < PROBE_COUNT; i++)
    {
        item = &probe_items[i * 9];
        probe_state = 0;
        ms_set_mapping(0);
        ms_set_palette_swap(0);
        if (item[0] == 0)
        {
            ms_set_mapping(item[2]);
            start = probe_vcount();
            ms_begin_frame();
            ms_draw_frame(item[1], item[5], item[6]);
            ms_end_frame();
        }
        else if (item[0] == 1)
        {
            ms_set_mapping(item[2]);
            ms_scene_player_init(&scene, item[1]);
            for (t = 0; t < (u16)item[4]; t++)
                ms_scene_player_tick(&scene);
            start = probe_vcount();
            ms_begin_frame();
            ms_draw_scene_player(&scene, item[5], item[6]);
            ms_end_frame();
        }
        else if (item[0] == 3)
        {
            start = probe_vcount();
            ms_begin_frame();
            ms_add_hw_sprite(item[5], item[6], item[1], (u8)item[2], (u8)item[3]);
            ms_end_frame();
        }
        else
        {
            ms_anim_player_init(&player, item[1]);
            for (t = 0; t < (u16)item[4]; t++)
                ms_anim_player_tick(&player);
            start = probe_vcount();
            ms_begin_frame();
            ms_draw_anim_player(&player, item[5], item[6]);
            ms_draw_anim_player_as(&player, item[2], item[3], item[7], item[8]);
            ms_end_frame();
        }
        now = probe_vcount();
        probe_lines = now >= start ? now - start : now + (snes_50hz ? 312 : 262) - start;
        probe_item = i;
        probe_state = 1;
        for (t = 0; t < PROBE_HOLD; t++)
            WaitForVBlank();
    }
    for (t = 0; t < PROBE_PALETTE_TICKS; t++)
    {
        WaitForVBlank();
        ms_palette_tick();  /* in vertical blank, as a game calls it */
    }
    ms_set_mapping(0);
    ms_set_palette_swap(0);
    if (MS_SCENE_COUNT == 0)
    {
        probe_state = 3;
        while (1)
            WaitForVBlank();
    }
    probe_state = 2;
    ms_scene_player_init(&scene, 0);
    while (1)
    {
        ms_begin_frame();
        ms_scene_player_tick(&scene);
        ms_draw_scene_player(&scene, @SCENE_X@, @SCENE_Y@);
        ms_end_frame();
        WaitForVBlank();
    }
    return 0;
}
"""

PROBE_LUA = r"""-- Generated by tools/check_snes_rom.py: one line per probe item (its draw's scanlines, the OAM buffer, the PPU's OAM),
-- the lag frames while the first scene plays, then video memory and the palettes.
local STATE, ITEM, LINES, OAM, LAG = @STATE@, @ITEM@, @LINES@, @OAM@, @LAG@
local HEX = {}
for i = 0, 255 do HEX[i] = string.format("%02x", i) end
local function hex(mem, base, size)
  local parts = {}
  for i = 0, size - 1 do parts[#parts + 1] = HEX[emu.read(base + i, mem, false)] end
  return table.concat(parts)
end
local current, lines, ram, ppu = -1, 0, "", ""
local playing, lag_start, frames = -1, 0, 0
local function flush()
  if current >= 0 then print("item " .. current .. " " .. lines .. " " .. ram .. " " .. ppu) end
  current = -1
end
local function finish()
  print("vram " .. hex(emu.memType.snesVideoRam, 0, 0x4000))
  print("cgram " .. hex(emu.memType.snesCgRam, 0, 512))
  emu.stop(0)
end
emu.addEventCallback(function()
  frames = frames + 1
  local state = emu.read16(STATE, emu.memType.snesMemory, false)
  if state == 1 then
    local item = emu.read16(ITEM, emu.memType.snesMemory, false)
    if item ~= current then
      flush()
      current = item
      lines = emu.read16(LINES, emu.memType.snesMemory, false)
      ram = hex(emu.memType.snesMemory, OAM, 544)
      ppu = ""
    else
      ppu = hex(emu.memType.snesSpriteRam, 0, 544)
    end
  elseif state == 2 then
    flush()
    if playing < 0 then
      playing = frames
      lag_start = emu.read16(LAG, emu.memType.snesMemory, false)
    elseif frames - playing >= @PLAY_FRAMES@ then
      print("lag " .. (emu.read16(LAG, emu.memType.snesMemory, false) - lag_start) .. " " .. (frames - playing))
      finish()
    end
  elseif state == 3 then
    flush()
    finish()
  end
  if frames > @MAX_FRAMES@ then
    print("timeout")
    emu.stop(1)
  end
end, emu.eventType.endFrame)
"""


def find_mesen(given: Optional[str]) -> Optional[str]:
    candidates = [given, os.environ.get("MESEN"), shutil.which("Mesen"), shutil.which("mesen"),
                  "/Applications/Mesen.app/Contents/MacOS/Mesen"]
    return next((c for c in candidates if c and os.path.exists(c)), None)


def find_pvsneslib(given: Optional[str]) -> Optional[Path]:
    candidates = [given, os.environ.get("PVSNESLIB_HOME"), str(DEMO / "third_party" / "pvsneslib")]
    return next((Path(c) for c in candidates if c and (Path(c) / "devkitsnes" / "snes_rules").exists()), None)


def probe_items(project: Project, mapping_count: int) -> List[Tuple[List[int], str, str]]:
    """(the C table's nine values, the host harness's command, a description) of everything the probe draws."""
    items = []
    for f, frame in enumerate(project.frames):
        for x, y in POSITIONS:
            items.append(([0, f, 0, 0, 0, x, y, 0, 0], f"frame {f} 0 {x} {y}", f"frame {frame.name} at {x},{y}"))
    for s, scene in enumerate(project.timeline_scenes):
        for m in range(mapping_count):
            for ticks in SCENE_TICKS:
                items.append(([1, s, m, 0, ticks, SCENE_X, SCENE_Y, 0, 0], f"scene {s} {m} {ticks} {SCENE_X} {SCENE_Y}",
                              f"scene {scene.name}, mapping {m}, tick {ticks}"))
    anim = next((i for i, a in enumerate(project.animations) if len(a.aframes) > 1), None)
    if anim is not None:
        mapping = 1 if mapping_count > 1 else 0
        swap = 1 if project.palette_swaps else 0
        left, right = SCENE_X - 40, SCENE_X + 40
        for ticks in (0, 30):
            items.append(([2, anim, mapping, swap, ticks, left, SCENE_Y, right, SCENE_Y],
                          f"versus {anim} {mapping} {swap} {ticks} {left} {SCENE_Y} {right} {SCENE_Y}",
                          f"animation {project.animations[anim].name} twice, tick {ticks}"))
    for large in (0, 255):
        for x, y in ((0, 0), (-3, 5), (250, 220), (-20, 100), (100, -10), (300, 50), (255, 223), (-15, -15)):
            items.append(([3, 0x123, 0x5A, large, 0, x, y, 0, 0], f"sprite {x} {y} {0x123} {0x5A} {large}",
                          f"a game's {'large' if large else 'small'} sprite at {x},{y}"))
    return items


def symbols(sym_file: Path) -> Dict[str, int]:
    found = {}
    for line in sym_file.read_text(errors="replace").splitlines():
        match = re.match(r"^([0-9a-fA-F]{8}) (\S+)$", line.strip())
        if match:
            found[match.group(2)] = int(match.group(1), 16)
    return found


def build_rom(project: Project, work: Path, pvsneslib: Path, items) -> Tuple[export_snes.SNESBakeContext, Path]:
    """The demo's runtime with the project's export and the probe program in ``work``, built; returns the bake and
    the ROM."""
    if work.exists():
        shutil.rmtree(work)
    (work / "src").mkdir(parents=True)
    (work / "inc").mkdir()
    shutil.copy(DEMO / "Makefile", work / "Makefile")
    for name in ("src/modsprite.c", "src/modsprite_draw.asm", "inc/modsprite.h"):
        shutil.copy(DEMO / name, work / name)
    ctx = snes_host.export(project, work)
    table = ",\n".join("    " + ", ".join(str(v) for v in values) for values, _command, _what in items)
    (work / "src" / "main.c").write_text(
        PROBE_C.replace("@COUNT@", str(len(items))).replace("@HOLD@", str(HOLD)).replace("@ITEMS@", table)
        .replace("@TICKS@", str(PALETTE_TICKS))
        .replace("@SCENE_X@", str(SCENE_X)).replace("@SCENE_Y@", str(SCENE_Y)))
    env = dict(os.environ, PVSNESLIB_HOME=str(pvsneslib))
    result = subprocess.run(["make"], cwd=work, env=env, capture_output=True, text=True)
    roms = sorted(work.glob("*.sfc"))
    if result.returncode != 0 or not roms:
        raise RuntimeError("the ROM did not build:\n" + (result.stdout + result.stderr)[-3000:])
    return ctx, roms[0]


def run_rom(mesen: str, rom: Path, work: Path, item_count: int, has_scene: bool) -> List[str]:
    found = symbols(rom.with_suffix(".sym"))
    missing = [n for n in ("probe_state", "probe_item", "probe_lines", "oamMemory", "lag_frame_counter")
               if n not in found]
    if missing:
        raise RuntimeError(f"symbols not found in {rom.with_suffix('.sym').name}: {', '.join(missing)}")
    max_frames = item_count * (HOLD + 2) + PALETTE_TICKS + (PLAY_FRAMES if has_scene else 0) + 600
    lua = (PROBE_LUA.replace("@STATE@", hex(found["probe_state"])).replace("@ITEM@", hex(found["probe_item"]))
           .replace("@LINES@", hex(found["probe_lines"])).replace("@OAM@", hex(found["oamMemory"]))
           .replace("@LAG@", hex(found["lag_frame_counter"])).replace("@PLAY_FRAMES@", str(PLAY_FRAMES))
           .replace("@MAX_FRAMES@", str(max_frames)))
    script = work / "probe.lua"
    script.write_text(lua)
    # Mesen's test runner stops itself after 100 s unless told otherwise; 840 s leaves this call's limit the last word.
    result = subprocess.run([mesen, "--testrunner", "--timeout=840", str(rom), str(script)], capture_output=True,
                            text=True, timeout=900)
    lines = result.stdout.splitlines()
    if not any(line.startswith("vram ") for line in lines):
        raise RuntimeError("Mesen did not finish the probe:\n" + (result.stdout + result.stderr)[-2000:])
    return lines


def check_project(path: Path, mesen: str, pvsneslib: Path, work: Path) -> bool:
    from models import ColourCycle

    project = Project.from_json(str(path))
    name = path.name
    if project.palettes and not any(p.cycles for p in project.palettes):  # something for ms_palette_tick to turn
        project.palettes[0].cycles = [ColourCycle(first=3, count=4, frames=3),
                                      ColourCycle(first=9, count=2, frames=5, reverse=True)]
    try:
        mapping_count = len(export_snes._resolve_mappings(project, "all"))
        items = probe_items(project, mapping_count)
        ctx, rom = build_rom(project, work, pvsneslib, items)
    except export_snes.ExportError as error:
        print(f"{name}: does not fit the SNES export ({error})")
        return True
    exe = snes_host.build(ctx, work)
    commands = [command for _values, command, _what in items] + ["cycle"] * (PALETTE_TICKS + 1)
    head, host_lines = snes_host.run(exe, work, commands)
    host_cgram = [int(v) for v in host_lines[-1].split()[1:]]  # the sprite palettes after PALETTE_TICKS ticks
    rom_lines = run_rom(mesen, rom, work, len(items), bool(project.timeline_scenes))
    shown: Dict[int, Tuple[int, str, str]] = {}
    lag = None
    vram = cgram = b""
    for line in rom_lines:
        fields = line.split(" ")
        if fields[0] == "item" and len(fields) == 5:
            shown[int(fields[1])] = (int(fields[2]), fields[3], fields[4])
        elif fields[0] == "lag":
            lag = (int(fields[1]), int(fields[2]))
        elif fields[0] == "vram":
            vram = bytes.fromhex(fields[1])
        elif fields[0] == "cgram":
            cgram = bytes.fromhex(fields[1])
    problems = []
    for index, (_values, _command, what) in enumerate(items):
        if index not in shown:
            problems.append(f"{what}: the script did not see it")
            continue
        _lines, ram, ppu = shown[index]
        host = snes_host.oam_of(host_lines[index])
        if ram != host:
            problems.append(f"{what}: the OAM buffer differs from the host build's")
        elif ppu and ppu != host:
            problems.append(f"{what}: the PPU's OAM differs from the OAM buffer")
    tables = ctx.tables_used * export_snes.TABLE_TILES * 32
    if vram[:tables] != bytes(ctx.tables[:tables]):
        problems.append("video memory does not hold the export's sprite tiles")
    rom_cgram = [int.from_bytes(cgram[2 * (128 + w):2 * (128 + w) + 2], "little") for w in range(128)]
    for line in range(min(len(ctx.palette_entries), export_snes.SPRITE_PALETTES)):  # the ones ms_init loads
        if rom_cgram[line * 16 + 1:line * 16 + 16] != host_cgram[line * 16 + 1:line * 16 + 16]:
            problems.append(f"sprite palette {line} differs from the host build's after {PALETTE_TICKS} palette ticks")
    for problem in problems[:20]:
        print(f"{name}: {problem}")
    if len(problems) > 20:
        print(f"{name}: ... and {len(problems) - 20} more")
    slowest = max(shown.items(), key=lambda kv: kv[1][0]) if shown else None
    summary = f"{name}: {len(shown)} of {len(items)} draws checked"
    if not problems:
        summary += (", every OAM like the host build's, video memory like the export, palettes like the host build's "
                    f"after {PALETTE_TICKS} palette ticks")
    if slowest:
        lines = slowest[1][0]
        summary += (f"; slowest draw {lines} scanlines ({lines * LINE_US / 1000:.1f} ms of a "
                    f"{LINES_PER_FRAME * LINE_US / 1000:.1f} ms frame): {items[slowest[0]][2]}")
    if lag is not None:
        summary += f"; {project.timeline_scenes[0].name} played {lag[1]} frames with {lag[0]} lag frames"
    print(summary)
    return not problems


def main() -> int:
    parser = argparse.ArgumentParser(description="Check the SNES runtime in a ROM against its host build (Mesen).")
    parser.add_argument("projects", nargs="*", help="Project files (default: the Prince of Persia and Adventurer "
                        "examples).")
    parser.add_argument("--mesen", help="The Mesen 2 executable (default: $MESEN, PATH, /Applications/Mesen.app).")
    parser.add_argument("--pvsneslib", help="PVSnesLib's folder (default: $PVSNESLIB_HOME, then "
                        "examples/snes/snes_demo/third_party/pvsneslib).")
    parser.add_argument("--keep", help="Build in this folder and keep it (default: a temporary folder).")
    args = parser.parse_args()
    mesen = find_mesen(args.mesen)
    pvsneslib = find_pvsneslib(args.pvsneslib)
    if not mesen or not pvsneslib or not snes_host.have_compiler():
        print("needs Mesen 2 (--mesen), PVSnesLib (--pvsneslib) and a C compiler (cc)")
        return 2
    paths = [Path(p).resolve() for p in args.projects] or DEFAULT_PROJECTS
    ok = True
    with tempfile.TemporaryDirectory() as tmp:
        base = Path(args.keep).resolve() if args.keep else Path(tmp)
        for path in paths:
            ok = check_project(path, mesen, pvsneslib, base / path.stem) and ok
    return 0 if ok else 1


if __name__ == "__main__":
    raise SystemExit(main())
