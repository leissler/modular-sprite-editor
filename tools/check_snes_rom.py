PROBE_LUA = r"""-- Generated by tools/check_snes_rom.py: one line per probe item (its draw's scanlines, the OAM buffer, the PPU's OAM,
-- its upload's scanlines and an Adler-32 of the slots' video memory), the lag frames while the first scene plays, then
-- video memory and the palettes.
local STATE, ITEM, LINES, UPLOAD, OAM, LAG, SUM = @STATE@, @ITEM@, @LINES@, @UPLOAD@, @OAM@, @LAG@, @SUM@
local SLOT_BYTES = @SLOT_BYTES@
local HEX = {}
for i = 0, 255 do HEX[i] = string.format("%02x", i) end
local function hex(mem, base, size)
  local parts = {}
  for i = 0, size - 1 do parts[#parts + 1] = HEX[emu.read(base + i, mem, false)] end
  return table.concat(parts)
end
local function adler(mem, base, size)
  local a, b = 1, 0
  for i = 0, size - 1 do
    a = (a + emu.read(base + i, mem, false)) % 65521
    b = (b + a) % 65521
  end
  return b * 65536 + a
end
local current, lines, ram, ppu, upload, slots, held, sum = -1, 0, "", "", 0, 0, 0, 0
local playing, lag_start, frames, cgram = -1, 0, 0, nil
local function flush()
  if current >= 0 then
    print("item " .. current .. " " .. lines .. " " .. ram .. " " .. ppu .. " " .. upload .. " " .. slots .. " " .. sum)
  end
  current = -1
end
local function finish()
  print("vram " .. hex(emu.memType.snesVideoRam, 0, 0x4000))
  print("cgram " .. (cgram or hex(emu.memType.snesCgRam, 0, 512)))
  emu.stop(0)
end
emu.addEventCallback(function()
  frames = frames + 1
  local state = emu.read16(STATE, emu.memType.snesMemory, false)
  if state == 1 then
    local item = emu.read16(ITEM, emu.memType.snesMemory, false)
    if item ~= current then
      flush()
      current = item
      lines = emu.read16(LINES, emu.memType.snesMemory, false)
      sum = emu.read16(SUM, emu.memType.snesMemory, false)
      ram = hex(emu.memType.snesMemory, OAM, 544)
      ppu, held = "", 0
    else
      held = held + 1
      ppu = hex(emu.memType.snesSpriteRam, 0, 544)
      upload = emu.read16(UPLOAD, emu.memType.snesMemory, false)
      if held == 1 and SLOT_BYTES > 0 then slots = adler(emu.memType.snesVideoRam, 0, SLOT_BYTES) end
    end
  elseif state == 2 then
    flush()
    if playing < 0 then
      playing = frames
      lag_start = emu.read16(LAG, emu.memType.snesMemory, false)
      cgram = hex(emu.memType.snesCgRam, 0, 512)  -- after the palette ticks, before the scene's ms_upload_tiles
    elseif frames - playing >= @PLAY_FRAMES@ then
      print("lag " .. (emu.read16(LAG, emu.memType.snesMemory, false) - lag_start) .. " " .. (frames - playing))
      finish()
    end
  elseif state == 3 then
    flush()
    finish()
  end
  if frames > @MAX_FRAMES@ then
    print("timeout")
    emu.stop(1)
  end
end, emu.eventType.endFrame)
"""


def find_mesen(given: Optional[str]) -> Optional[str]:
    candidates = [given, os.environ.get("MESEN"), shutil.which("Mesen"), shutil.which("mesen"),
                  "/Applications/Mesen.app/Contents/MacOS/Mesen"]
    return next((c for c in candidates if c and os.path.exists(c)), None)


def find_pvsneslib(given: Optional[str]) -> Optional[Path]:
    candidates = [given, os.environ.get("PVSNESLIB_HOME"), str(DEMO / "third_party" / "pvsneslib")]
    return next((Path(c) for c in candidates if c and (Path(c) / "devkitsnes" / "snes_rules").exists()), None)


KINDS = {"frame": 0, "module": 1, "sprite": 2}
SPRITE_LIMIT = 128


def crowd(seed: int, count: int, project: Project, mapping_count: int) -> List[Tuple[str, int, int, int, int, int, int]]:
    """A picture of frames, modules and a few sprites of the game's own across the screen and its edges, front to back:
    (kind, index, mapping, flip, give-way level 0-3, x, y); a sprite's index its tile, its mapping its attribute, its
    flip 1 when it is large."""
    import random

    rng = random.Random(seed)
    draws = []
    for _n in range(count):
        kind = "module" if project.modules and rng.random() < 0.25 else "frame"
        draws.append((kind, rng.randrange(len(project.modules if kind == "module" else project.frames)),
                      rng.randrange(mapping_count), rng.randrange(4), rng.choice((0, 0, 0, 1, 2, 3)),
                      rng.randrange(-40, snes_host.SCREEN_W + 40), rng.randrange(-40, snes_host.SCREEN_H + 40)))
    for _n in range(count // 4):
        draws.insert(rng.randrange(len(draws) + 1), ("sprite", 0x100 + rng.randrange(16), 0x22, rng.randrange(2),
                                                     rng.choice((0, 1, 2)), rng.randrange(-10, snes_host.SCREEN_W),
                                                     rng.randrange(-10, snes_host.SCREEN_H)))
    return draws


def given_way(costs: List[int], levels: List[int]) -> set:
    """The draws that give way past the sprite limit: level 1 first, within a level the last drawn first, as many as
    the excess (modsprite.h, ms_set_give_way)."""
    excess, out = sum(costs) - SPRITE_LIMIT, set()
    for level in sorted({lv for lv in levels if lv > 0}):
        for n in reversed(range(len(costs))):
            if excess > 0 and levels[n] == level and costs[n] > 0:
                out.add(n)
                excess -= costs[n]
    return out


def picture_command(draws, levels: bool, cached: bool) -> str:
    """A picture as snes_host's commands (one output line: the frame's end)."""
    puts = [f"put sprite {x} {y} {i} {m} {f} {lv if levels else 0}" if k == "sprite" else
            f"put {k} {i} {m} {f} {lv if levels else 0} {x} {y}" for k, i, m, f, lv, x, y in draws]
    return "\n".join((["usecache"] if cached else []) + ["begin"] + puts + ["end"] + (["uncached"] if cached else []))


def probe_items(project: Project, mapping_count: int, bake: Optional[export_snes.SNESBakeContext] = None,
                cache_tiles: int = 0) -> Tuple[List[Tuple[List[int], str, str]], List[List[int]]]:
    """(the C table's nine values, the host harness's command, a description) of everything the probe draws, and the
    pictures' draws (seven values each)."""
    items = []
    for f, frame in enumerate(project.frames):
        for x, y in POSITIONS:
            items.append(([0, f, 0, 0, 0, x, y, 0, 0], f"frame {f} 0 {x} {y}", f"frame {frame.name} at {x},{y}"))
    for f, frame in enumerate(project.frames):
        for p, (x, y) in enumerate(POSITIONS):
            flip = 1 + (f + p) % 3  # each frame mirrored each way, each way at another position
            items.append(([4, f, 0, flip, 0, x, y, 0, 0], f"flipped {f} 0 {flip} {x} {y}",
                          f"frame {frame.name} mirrored {flip} at {x},{y}"))
    for m, module in enumerate(project.modules):
        flip, (x, y) = m % 4, POSITIONS[m % len(POSITIONS)]
        items.append(([5, m, 0, flip, 0, x, y, 0, 0], f"module {m} 0 {flip} {x} {y}",
                      f"module {module.name} {'mirrored ' + str(flip) if flip else 'as it is'} at {x},{y}"))
    if project.frames:  # past the 128 sprites: the fast loops' room test fails part way, the careful ones drop sprites
        busiest = max(range(len(project.frames)), key=lambda f: len(project.frames[f].fmodules))
        for f, count, (x, y), dx in ((busiest, 12, (20, 112), 20), (busiest, 16, (-30, 216), 21), (0, 24, (4, 10), 11)):
            items.append(([6, f, 0, count, 0, x, y, dx, 0], f"crowd {f} 0 {count} {x} {y} {dx}",
                          f"frame {project.frames[f].name} {count} times from {x},{y}, {dx} apart, the flips in turn"))
    for s, scene in enumerate(project.timeline_scenes):
        for m in range(mapping_count):
            for ticks in SCENE_TICKS:
                items.append(([1, s, m, 0, ticks, SCENE_X, SCENE_Y, 0, 0], f"scene {s} {m} {ticks} {SCENE_X} {SCENE_Y}",
                              f"scene {scene.name}, mapping {m}, tick {ticks}"))
    anim = next((i for i, a in enumerate(project.animations) if len(a.aframes) > 1), None)
    if anim is not None:
        mapping = 1 if mapping_count > 1 else 0
        swap = 1 if project.palette_swaps else 0
        left, right = SCENE_X - 40, SCENE_X + 40
        for ticks in (0, 30):
            items.append(([2, anim, mapping, swap, ticks, left, SCENE_Y, right, SCENE_Y],
                          f"versus {anim} {mapping} {swap} {ticks} {left} {SCENE_Y} {right} {SCENE_Y}",
                          f"animation {project.animations[anim].name} twice, tick {ticks}"))
        for flip in range(4):  # the second the other way left to right: they face each other
            for ticks in (0, 30):
                items.append(([9, anim, mapping, swap, ticks, left, SCENE_Y, right, flip],
                              f"facing {anim} {mapping} {swap} {flip} {ticks} {left} {SCENE_Y} {right} {SCENE_Y}",
                              f"animation {project.animations[anim].name} twice facing, the first mirrored {flip}, "
                              f"tick {ticks}"))
    for large in (0, 255):
        for x, y in ((0, 0), (-3, 5), (250, 220), (-20, 100), (100, -10), (300, 50), (255, 223), (-15, -15)):
            items.append(([3, 0x123, 0x5A, large, 0, x, y, 0, 0], f"sprite {x} {y} {0x123} {0x5A} {large}",
                          f"a game's {'large' if large else 'small'} sprite at {x},{y}"))
    items.append(([8, 0, 0, 0, 0, 0, 0, 0, 0], "checksum",
                  "every frame's and module's sprites and bounds, every frame's hitboxes and points mirrored"))
    draws: List[List[int]] = []
    if bake is None or not project.frames:
        return items, draws
    # Pictures (last: the first give-way level stays on): each drawn as it is, then only the draws that stay (what a
    # game that measured the picture first submits a second time), then with its levels; streamed also through the
    # slot cache, three times (the first ones upload). The first fits.
    pictures = []
    for seed in range(400):
        picture = crowd(seed, 6 + seed % 18, project, mapping_count)
        costs = [snes_host.draw_cost(bake, k, i, m, f, x, y) for k, i, m, f, _lv, x, y in picture]
        gone = given_way(costs, [d[4] for d in picture])
        fits = sum(costs) <= SPRITE_LIMIT
        if (not pictures and fits) or (pictures and not fits and gone):
            pictures.append((picture, gone, sum(costs)))
        if len(pictures) == 6:
            break
    plain, kept, levels, watched, cached = [], [], [], [], []
    for p, (picture, gone, asked) in enumerate(pictures):
        first = len(draws)
        draws += [[KINDS[k], i, m, f, lv, x, y] for k, i, m, f, lv, x, y in picture]
        stays = [d for n, d in enumerate(picture) if n not in gone]
        plain.append(([7, first, len(picture), 0, 0, 0, 0, 0, 0], picture_command(picture, False, False),
                      f"picture {p} ({asked} sprites asked) as it is"))
        first_kept = len(draws)
        draws += [[KINDS[k], i, m, f, lv, x, y] for k, i, m, f, lv, x, y in stays]
        kept.append(([7, first_kept, len(stays), 0, 0, 0, 0, 0, 0], picture_command(stays, False, False),
                      f"picture {p}: the draws that stay"))
        levels.append(([7, first, len(picture), 1, 0, 0, 0, 0, 0], picture_command(picture, True, False),
                       f"picture {p} with its give-way levels ({len(gone)} give way)"))
        watched.append(([7, first, len(picture), 0, 0, 0, 0, 0, 0], picture_command(picture, False, False),
                        f"picture {p} watched (levels on, none set)"))
        if cache_tiles:
            cached += [([7, first, len(picture), 3, 0, 0, 0, 0, 0], picture_command(picture, True, True),
                        f"picture {p} through the slot cache with its levels, time {n}") for n in range(3)]
    hits = []
    if cache_tiles:  # eight draws of one frame: through the default slot (it holds it), and through the cache
        frame = max(range(len(project.frames)),
                    key=lambda f: snes_host.draw_cost(bake, "frame", f, 0, 0, snes_host.SCREEN_W // 2, 112))
        first = len(draws)
        picture = [("frame", frame, 0, 0, 0, 40 + 24 * k, 112) for k in range(8)]
        draws += [[KINDS[k], i, m, f, lv, x, y] for k, i, m, f, lv, x, y in picture]
        for cached_ in (False, True):
            hits += [([7, first, len(picture), 2 if cached_ else 0, 0, 0, 0, 0, 0],
                      picture_command(picture, False, cached_),
                      f"hits: frame {project.frames[frame].name} 8 times through "
                      f"{'the slot cache' if cached_ else 'the default slot'}, time {n}") for n in range(3)]
    return items + plain + kept + levels + watched + cached + hits, draws


def symbols(sym_file: Path) -> Dict[str, int]:
    found = {}
    for line in sym_file.read_text(errors="replace").splitlines():
        match = re.match(r"^([0-9a-fA-F]{8}) (\S+)$", line.strip())
        if match:
            found[match.group(2)] = int(match.group(1), 16)
    return found


def build_rom(project: Project, work: Path, pvsneslib: Path, items, mode: str = "parts", draws=(),
              cache: Tuple[int, int] = (0, 0)) -> Tuple[export_snes.SNESBakeContext, Path]:
    """The demo's runtime with the project's export (in ``mode``) and the probe program in ``work``, built (with the
    pictures' draws and the slot cache's first tile and tiles); returns the bake and the ROM."""
    if work.exists():
        shutil.rmtree(work)
    (work / "src").mkdir(parents=True)
    (work / "inc").mkdir()
    shutil.copy(DEMO / "Makefile", work / "Makefile")
    for name in ("src/modsprite.c", "src/modsprite_draw.asm", "inc/modsprite.h"):
        shutil.copy(DEMO / name, work / name)
    ctx = snes_host.export(project, work, mode=mode)
    table = ",\n".join("    " + ", ".join(str(v) for v in values) for values, _command, _what in items)
    (work / "src" / "main.c").write_text(
        PROBE_C.replace("@COUNT@", str(len(items))).replace("@HOLD@", str(HOLD)).replace("@ITEMS@", table)
        .replace("@DRAW_COUNT@", str(len(draws))).replace("@DRAWS@", ",\n".join(
            "    " + ", ".join(str(v) for v in values) for values in draws) or "    0")
        .replace("@CACHE_FIRST@", str(cache[0])).replace("@CACHE_TILES@", str(cache[1]))
        .replace("@TICKS@", str(PALETTE_TICKS))
        .replace("@SCENE_X@", str(SCENE_X)).replace("@SCENE_Y@", str(SCENE_Y)))
    env = dict(os.environ, PVSNESLIB_HOME=str(pvsneslib))
    result = subprocess.run(["make"], cwd=work, env=env, capture_output=True, text=True)
    roms = sorted(work.glob("*.sfc"))
    if result.returncode != 0 or not roms:
        raise RuntimeError("the ROM did not build:\n" + (result.stdout + result.stderr)[-3000:])
    return ctx, roms[0]


def run_rom(mesen: str, rom: Path, work: Path, item_count: int, has_scene: bool, slot_bytes: int = 0) -> List[str]:
    found = symbols(rom.with_suffix(".sym"))
    missing = [n for n in ("probe_state", "probe_item", "probe_lines", "probe_upload_lines", "probe_sum", "oamMemory",
                           "lag_frame_counter") if n not in found]
    if missing:
        raise RuntimeError(f"symbols not found in {rom.with_suffix('.sym').name}: {', '.join(missing)}")
    max_frames = item_count * (HOLD + 2) + PALETTE_TICKS + (PLAY_FRAMES if has_scene else 0) + 600
    lua = (PROBE_LUA.replace("@STATE@", hex(found["probe_state"])).replace("@ITEM@", hex(found["probe_item"]))
           .replace("@LINES@", hex(found["probe_lines"])).replace("@UPLOAD@", hex(found["probe_upload_lines"]))
           .replace("@SLOT_BYTES@", str(slot_bytes)).replace("@OAM@", hex(found["oamMemory"]))
           .replace("@LAG@", hex(found["lag_frame_counter"])).replace("@SUM@", hex(found["probe_sum"]))
           .replace("@PLAY_FRAMES@", str(PLAY_FRAMES))
           .replace("@MAX_FRAMES@", str(max_frames)))
    script = work / "probe.lua"
    script.write_text(lua)
    result = run_mesen(mesen, rom, script)
    lines = result.stdout.splitlines()
    if not any(line.startswith("vram ") for line in lines):
        raise RuntimeError("Mesen did not finish the probe:\n" + (result.stdout + result.stderr)[-2000:])
    return lines


def run_mesen(mesen: str, rom: Path, script: Path) -> subprocess.CompletedProcess:
    """Mesen's headless test runner playing the ROM with the Lua script (what the script prints is the output)."""
    # The test runner stops itself after 100 s unless told otherwise; 840 s leaves this call's limit the last word.
    # On Linux, Mesen 2.1's core (with a C++ library of its own) dies with std::bad_cast while it loads when .NET has
    # loaded the system's ICU first: run .NET without ICU.
    env = dict(os.environ)
    if sys.platform.startswith("linux"):
        env.setdefault("DOTNET_SYSTEM_GLOBALIZATION_INVARIANT", "1")
    return subprocess.run([mesen, "--testrunner", "--timeout=840", str(rom), str(script)], capture_output=True,
                          text=True, timeout=900, env=env)


def check_project(path: Path, mesen: str, pvsneslib: Path, work: Path, mode: str = "parts",
                  timings: Optional[Path] = None) -> bool:
    import zlib

    from models import ColourCycle

    project = Project.from_json(str(path))
    name = path.name if mode == "parts" else f"{path.name} ({mode})"
    if project.palettes and not any(p.cycles for p in project.palettes):  # something for ms_palette_tick to turn
        project.palettes[0].cycles = [ColourCycle(first=3, count=4, frames=3),
                                      ColourCycle(first=9, count=2, frames=5, reverse=True)]
    try:
        mappings = console_bake.resolve_mappings(project, "all")
        bake = export_snes.SNESBakeContext(project, mappings, mode=mode)  # the pictures' sprites and slots
        bake.bake()
        cache = (0, 0)
        if bake.streamed:  # the slot cache after the default slot and the second one, when it holds a few slots
            first = -(-(bake.tile_end + bake.slot_tiles) // bake.slot_align) * bake.slot_align
            if export_snes.SPRITE_TILES - first >= 2 * bake.slot_tiles:
                cache = (first, export_snes.SPRITE_TILES - first)
        items, draws = probe_items(project, len(mappings), bake, cache[1])
        ctx, rom = build_rom(project, work, pvsneslib, items, mode, draws, cache)
    except export_snes.ExportError as error:
        print(f"{name}: does not fit the SNES export ({error})")
        return True
    exe = snes_host.build(ctx, work)
    prefix = ["vramdump 512", f"cache {cache[0]} {cache[1]}", "uncached"] if cache[1] else []
    commands = prefix + [command for _values, command, _what in items] + ["cycle"] * (PALETTE_TICKS + 1)
    head, host_lines = snes_host.run(exe, work, commands)
    host_cgram = [int(v) for v in host_lines[-1].split()[1:]]  # the sprite palettes after PALETTE_TICKS ticks
    # the default slot and the second (and the slot cache's pool after them)
    slot_bytes = 0 if not ctx.streamed else (export_snes.SPRITE_TILES if cache[1] else ctx.tile_end + ctx.slot_tiles) * 32
    rom_lines = run_rom(mesen, rom, work, len(items), bool(project.timeline_scenes), slot_bytes)
    shown: Dict[int, Tuple[int, str, str, int, int, int]] = {}
    lag = None
    vram = cgram = b""
    for line in rom_lines:
        fields = line.split(" ")
        if fields[0] == "item" and len(fields) == 8:
            shown[int(fields[1])] = (int(fields[2]), fields[3], fields[4], int(fields[5]), int(fields[6]),
                                     int(fields[7]))
        elif fields[0] == "lag":
            lag = (int(fields[1]), int(fields[2]))
        elif fields[0] == "vram":
            vram = bytes.fromhex(fields[1])
        elif fields[0] == "cgram":
            cgram = bytes.fromhex(fields[1])
    problems = []
    host_vram = bytes(slot_bytes)
    for index, (_values, _command, what) in enumerate(items):
        draw = snes_host.parse_draw(host_lines[index])
        if draw.get("vram"):
            host_vram = (draw["vram"] + bytes(slot_bytes))[:slot_bytes]
        if index not in shown:
            problems.append(f"{what}: the script did not see it")
            continue
        _lines, ram, ppu, _upload, slots, query_sum = shown[index]
        if ram != draw["oam"]:
            problems.append(f"{what}: the OAM buffer differs from the host build's")
        if items[index][0][0] == 8 and query_sum != int(host_lines[index].split(" ")[1]):
            problems.append(f"{what}: the queries' sum differs from the host build's")
        elif ppu and ppu != draw["oam"]:
            problems.append(f"{what}: the PPU's OAM differs from the OAM buffer")
        if slot_bytes and slots != zlib.adler32(host_vram):
            problems.append(f"{what}: the slots' video memory differs from the host build's")
    tables = ctx.tables_used * export_snes.TABLE_TILES * 32
    if vram[:tables] != bytes(ctx.tables[:tables]):
        problems.append("video memory does not hold the export's sprite tiles")
    rom_cgram = [int.from_bytes(cgram[2 * (128 + w):2 * (128 + w) + 2], "little") for w in range(128)]
    for line in range(min(len(ctx.palette_entries), export_snes.SPRITE_PALETTES)):  # the ones ms_init loads
        if rom_cgram[line * 16 + 1:line * 16 + 16] != host_cgram[line * 16 + 1:line * 16 + 16]:
            problems.append(f"sprite palette {line} differs from the host build's after {PALETTE_TICKS} palette ticks")
    for problem in problems[:20]:
        print(f"{name}: {problem}")
    if len(problems) > 20:
        print(f"{name}: ... and {len(problems) - 20} more")
    if timings is not None:  # each draw's scanlines and its upload's, with what it uploaded
        rows = ["item\tdraw\tupload\tlines\ttiles\truns\tgroups\tcost\twhat"]
        for index, (_values, _command, what) in enumerate(items):
            if index in shown:
                draw = snes_host.parse_draw(host_lines[index])
                queued = [ctx.load_lists[n] for n in draw.get("queued", [])]
                rows.append("\t".join(str(v) for v in (
                    index, shown[index][0], shown[index][3], len(queued), sum(t for _r, t, _c in queued),
                    sum(len(r) for r, _t, _c in queued), sum(len({run[0] for run in r}) for r, _t, _c in queued),
                    sum(c for _r, _t, c in queued), what)))
        with open(timings, "a", encoding="utf-8") as out:
            out.write("\n".join(rows) + "\n")
    single = {index: values for index, values in shown.items() if items[index][0][0] not in (6, 7, 8)}  # one draw each
    slowest = max(single.items(), key=lambda kv: kv[1][0]) if single else None
    summary = f"{name}: {len(shown)} of {len(items)} draws checked"
    if not problems:
        summary += (", every OAM like the host build's, video memory like the "
                    f"{'host build' if ctx.streamed else 'export'}'s, palettes like the host build's after "
                    f"{PALETTE_TICKS} palette ticks")
    if slowest:
        lines = slowest[1][0]
        summary += (f"; slowest draw {lines} scanlines ({lines * LINE_US / 1000:.1f} ms of a "
                    f"{LINES_PER_FRAME * LINE_US / 1000:.1f} ms frame): {items[slowest[0]][2]}")
    if ctx.streamed and shown:
        upload = max(shown.items(), key=lambda kv: kv[1][3])
        summary += f"; slowest upload {upload[1][3]} scanlines: {items[upload[0]][2]}"
    if lag is not None:
        summary += f"; {project.timeline_scenes[0].name} played {lag[1]} frames with {lag[0]} lag frames"
    print(summary)
    pictures = picture_timings(items, shown)
    if pictures:
        print(f"{name}: {pictures}")
    return not problems


def picture_timings(items, shown) -> str:
    """The pictures' scanlines: drawn as they are, with their give-way levels, and what a game that measures a picture
    first and submits it again without what gives way spends (the first draw and the draws that stay)."""
    by_kind: Dict[str, Dict[int, int]] = {}
    for index, (_values, _command, what) in enumerate(items):
        match = re.match(r"picture (\d+)(.*)", what)
        if match and index in shown:
            kind = ("cached" if "cache" in match.group(2) else "watched" if "watched" in match.group(2)
                    else "levels" if "levels" in match.group(2) else "kept" if "stay" in match.group(2) else "plain")
            by_kind.setdefault(kind, {})[int(match.group(1))] = shown[index][0]  # (through the cache: the last time)
    plain, kept, levels = by_kind.get("plain", {}), by_kind.get("kept", {}), by_kind.get("levels", {})
    watched = by_kind.get("watched", {})
    if not plain or 0 not in levels:
        return ""
    over = [p for p in plain if p and p in levels and p in kept]
    text = (f"a picture that fits: {plain[0]} scanlines as it is, {levels[0]} with give-way levels"
            + (f" ({watched[0]} watched, none set)" if 0 in watched else ""))
    if over:
        text += ("; pictures over the limit: {} scanlines with give-way levels, {} drawing them and again without what "
                 "gives way (as it is {}, watched with none set {})").format(
                     "/".join(str(levels[p]) for p in over), "/".join(str(plain[p] + kept[p]) for p in over),
                     "/".join(str(plain[p]) for p in over), "/".join(str(watched.get(p, "-")) for p in over))
    cached = by_kind.get("cached", {})
    if cached:
        text += "; through the slot cache, the third time: " + "/".join(str(cached[p]) for p in sorted(cached))
    hits = {what.split(" through ")[1].split(",")[0]: shown[index][0] for index, (_v, _c, what) in enumerate(items)
            if what.startswith("hits:") and what.endswith("time 2") and index in shown}
    if hits:
        text += ("; one frame 8 times, held: " + ", ".join(f"{lines} scanlines through {slot}"
                                                         for slot, lines in sorted(hits.items())))
    return text


def main() -> int:
    parser = argparse.ArgumentParser(description="Check the SNES runtime in a ROM against its host build (Mesen).")
    parser.add_argument("projects", nargs="*", help="Project files (default: the Prince of Persia and Adventurer "
                        "examples).")
    parser.add_argument("--mesen", help="The Mesen 2 executable (default: $MESEN, PATH, /Applications/Mesen.app).")
    parser.add_argument("--pvsneslib", help="PVSnesLib's folder (default: $PVSNESLIB_HOME, then "
                        "examples/snes/snes_demo/third_party/pvsneslib).")
    parser.add_argument("--keep", help="Build in this folder and keep it (default: a temporary folder).")
    parser.add_argument("--mode", choices=export_snes.MODES, default="parts",
                        help="How the export stores the sprites (docs/EXPORT_MODES.md); default: parts.")
    parser.add_argument("--timings", help="Add each draw's scanlines (and its upload's) to this file, tab-separated.")
    args = parser.parse_args()
    mesen = find_mesen(args.mesen)
    pvsneslib = find_pvsneslib(args.pvsneslib)
    if not mesen or not pvsneslib or not snes_host.have_compiler():
        print("needs Mesen 2 (--mesen), PVSnesLib (--pvsneslib) and a C compiler (cc)")
        return 2
    paths = [Path(p).resolve() for p in args.projects] or DEFAULT_PROJECTS
    ok = True
    with tempfile.TemporaryDirectory() as tmp:
        base = Path(args.keep).resolve() if args.keep else Path(tmp)
        for path in paths:
            ok = check_project(path, mesen, pvsneslib, base / path.stem, args.mode,
                               Path(args.timings) if args.timings else None) and ok
    return 0 if ok else 1


if __name__ == "__main__":
    raise SystemExit(main())
