"""Build the SNES runtime into a ROM with PVSnesLib and check what it draws on the console against the host build of
the same runtime, which tests/test_snes_runtime_draw.py checks against the editor (needs PVSnesLib and Mesen 2;
neither is needed by the editor or its tests).

For each project: exports it (examples/snes/tools/export_snes.py) into a copy of the SNES demo with a probe program in
place of the demo's main.c and builds the ROM. Mesen's headless test runner plays it with a Lua script that reads the
OAM buffer and the PPU's OAM after every draw, then video memory and the palettes. The probe draws every frame at three
positions, as it is and mirrored (ms_draw_frame_flipped, the three ways in turn), every module (ms_draw_module_flipped:
as it is or mirrored, in turn), each scene at a few moments with every mapping, one animation twice with
ms_draw_anim_player_as (the second time with another mapping and palette swap) and twice facing itself
(ms_draw_anim_player_flipped each way, then ms_draw_anim_player_as_flipped the other way left to right), a game's own
sprites (ms_add_hw_sprite) across the screen's edges, the sum of every frame's and module's sprites and bounds
(ms_frame_sprites, ms_frame_bounds, ...) and of every frame's hitboxes and points mirrored each way (ms_flip_hitbox,
ms_flip_point) and pictures of many draws, one that fits and some past the 128 sprites: as
they are, only the draws that would stay, and with give-way levels (ms_set_give_way: written draws taken out of the
OAM buffer, waiting ones drawn after), timing each draw with the PPU's V counter; then it turns the colour
cycles (two added to the first palette when it has none) for 47 video frames and plays the first scene for ten
seconds, counting lag frames (frames the game was not ready for). Every OAM must equal the host build's byte for byte,
video memory the export's sprite tiles and the sprite palettes the host build's after as many palette ticks.

With --mode parts_streamed or frames_streamed the export is streamed: after each draw the probe uploads the tiles
(ms_upload_tiles, timed too) and the script checks the slots' video memory after every draw against the host build's
(an Adler-32 of it), in place of the sprite tables at the end; the pictures are also drawn through a slot cache in the
sprite tiles after the default slot and the second one (ms_slot_cache_init), when they leave room for one.

Usage (from the repository root):
    python3 tools/check_snes_rom.py [PROJECT.json ...] [--mode MODE] [--mesen PATH] [--pvsneslib DIR] [--keep DIR]
"""

